"""drive_rules.py - the Drive-store selection rules and the .gitignore block markers, in one place (CPME practice).

Shared by harness/scripts/drive_store.py (the only writer of pointers and of the managed .gitignore block),
harness/checks/drive_pointers.py (CI: no selected file is tracked) and harness/scripts/track.py (the daily commit
refuses a selected file without its pointer, and adds .gitignore when its managed block changed). Before
2026-10-07 the check and the store each carried their own copy of the rule; a commit then took a 10.2 MB file the
store had already moved.

The rules (job/drive-store.yaml, one store for the whole job): every file at or above `large_file_bytes`, and every file with a listed extension
under a listed directory, lives in the Google Drive folder; git tracks its `<file>.drive` pointer instead.

Pure functions, no I/O except `load`. `load` needs pyyaml; everything else is stdlib.
"""
from __future__ import annotations

from fnmatch import fnmatchcase
from pathlib import Path

POINTER_SUFFIX = ".drive"
BLOCK_BEGIN = ("# >>> drive-store: generated by harness/scripts/drive_store.py from job/drive-store.yaml; "
               "edit the YAML, not this block >>>")
# Older markers; still recognized so an old block is replaced, not doubled.
OLD_BLOCK_BEGINS = ("# >>> drive-store: generated by harness/scripts/drive_store.py from the project's drive-store.yaml; "
                    "edit the YAML, not this block >>>",)


def under(rel: str, d: str) -> bool:
    """rel is d itself or inside it. A `*` segment in d matches one folder name, so `job/*/04_Vendor_Data`
    covers every project folder (one job-level store, Bob, chat, 2026-10-26)."""
    rp_, dp = rel.split("/"), d.split("/")
    return len(rp_) >= len(dp) and all(fnmatchcase(a, b) for a, b in zip(rp_, dp))
BLOCK_END = "# <<< drive-store <<<"


def block_begin_index(lines: list[str]) -> int:
    """Index of the managed block's first line (current or an old marker), or -1."""
    return next((i for i, ln in enumerate(lines) if ln == BLOCK_BEGIN or ln in OLD_BLOCK_BEGINS), -1)


def normalize(raw: dict | None) -> dict:
    """The YAML as the rules use it: directories {dir: {ext, ...}} with no slashes or dots, exclude [dir, ...]."""
    cfg = dict(raw or {})
    cfg["directories"] = {d.strip("/"): {e.lower().lstrip(".") for e in exts}
                          for d, exts in (cfg.get("directories") or {}).items()}
    cfg["exclude"] = [e.strip("/") for e in (cfg.get("exclude") or [])]
    return cfg


def load(path: Path) -> dict:
    """job/drive-store.yaml, normalized. Raises OSError when missing and KeyError on a missing required key."""
    import yaml  # pyyaml, pinned in harness/requirements.txt
    cfg = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    for key in ("drive_folder_url", "large_file_bytes", "directories"):
        if key not in cfg:
            raise KeyError(key)
    return normalize(cfg)


def rule_for(rel: str, size: int, cfg: dict) -> str | None:
    """Which rule selects this repo-relative (posix) path: 'size', 'dir', or None. Pointers are never selected."""
    if rel.endswith(POINTER_SUFFIX):
        return None
    limit = int(cfg.get("large_file_bytes") or 0)
    if limit and size >= limit:
        return "size"
    name = rel.rsplit("/", 1)[-1]
    ext = name.rsplit(".", 1)[-1].lower() if "." in name else ""
    for d, exts in cfg["directories"].items():
        if ext in exts and len(rel.split("/")) > len(d.split("/")) and under(rel, d):
            return "dir"
    return None


def excluded(rel: str, cfg: dict) -> bool:
    return any(under(rel, e) for e in cfg["exclude"])


def pointer_rel(rel: str) -> str:
    return rel + POINTER_SUFFIX


def split_block(text: str) -> tuple[list[str], list[str] | None]:
    """(lines outside the managed block, the block's lines including its markers or None when there is none).
    Blank lines at the seams are dropped from the outside part, so adding the block to a file does not count as an
    outside change."""
    lines = (text or "").splitlines()
    i = block_begin_index(lines)
    if i >= 0 and BLOCK_END in lines[i:]:
        j = lines.index(BLOCK_END, i)
        if j > i:
            before, after = lines[:i], lines[j + 1:]
            while before and not before[-1].strip():
                before.pop()
            while after and not after[0].strip():
                after.pop(0)
            return before + after, lines[i:j + 1]
    while lines and not lines[-1].strip():
        lines.pop()
    return lines, None


def gitignore_change(old: str, new: str) -> str:
    """How .gitignore `new` differs from `old`: 'same', 'block' (only inside the drive-store managed block, i.e.
    written by drive_store.py pointers) or 'outside' (some other line changed too)."""
    if (old or "").splitlines() == (new or "").splitlines():
        return "same"
    old_out, old_blk = split_block(old)
    new_out, new_blk = split_block(new)
    if [ln.rstrip() for ln in old_out] == [ln.rstrip() for ln in new_out]:
        return "block" if old_blk != new_blk else "same"
    return "outside"
